export const EXERCISE_BY_ID: Record<string, Exercise> = Object.fromEntries(EXERCISES.map((e) => [e.id, e]));

let loadedDetails: Record<string, ExerciseDetail> | null = null;
let detailsPromise: Promise<Record<string, ExerciseDetail>> | null = null;

/** Loads the detail-text chunk (once); later calls reuse the same promise. */
export function loadExerciseDetails(): Promise<Record<string, ExerciseDetail>> {
  detailsPromise ??= import('./exerciseDetails').then((m) => (loadedDetails = m.EXERCISE_DETAILS));
  return detailsPromise;
}

/** The detail text if it has already been loaded, so pages can render it without waiting. */
export const getLoadedExerciseDetails = () => loadedDetails;

/** Compact age label used in dense lists, e.g. "U10 – U13" → "U10–13". */
export function shortAgeLabel(label: string): string {
  return label.replace(/ – U/, '–');
}

/** Short material names used in the training builder summary. */
export function materialNames(e: Exercise): string[] {
  return e.materials.map((m) => (/^Grote? doel/.test(m.name) && m.qty !== '1' ? `${m.qty} doelen` : m.name === 'Doeltjes' ? `${m.qty} doeltjes` : m.name));
}
