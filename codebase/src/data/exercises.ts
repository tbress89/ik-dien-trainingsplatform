export type Theme = (typeof THEMES)[number];

export type AgeGroup = 'U6–9' | 'U10–13' | 'U14–15' | 'U16–21';

/**
 * List-level data for an exercise: everything the dashboard, builder, filters and the top of the
 * detail page need. The longer coaching text is in ExerciseDetail.
 */
export interface Exercise {
  id: string;
  title: string;
  variant: Variant;
  type: ExerciseType;
  phase: Phase;
  /** Training themes this exercise fits; drives the builder's theme picker. */
  themes: Theme[];
  ages: AgeGroup[];
  ageLabel: string;
  /** 1 = Basis, 2 = Gemiddeld, 3 = Gevorderd */
  diff: 1 | 2 | 3;
  /** Minimum number of players needed, used by the player filter. */
  pmin: number;
  players: string;
  playersDetail?: string;
  min: number;
  /** 1–5 */
  intensity: number;
  field: string;
  materials: { name: string; qty: string }[];
}

/**
 * Coaching text shown only on an exercise's detail page. It lives in exerciseDetails.ts, keyed by
 * exercise id, and is loaded as a separate chunk on demand (see loadExerciseDetails), which keeps
 * the main bundle small.
 */
export interface ExerciseDetail {
  summary: string;
  steps: { title: string; text: string }[];
  easier: string;
  harder: string;
  objectives: string[];
  coaching: string[];
  /**
   * Optional `[label, hint]` stages for the detail-page diagram. With two or more, the page shows a
   * button per stage and stage `i` reveals the arrows whose `at` is ≤ i (the last stage shows everything).
   * With one, only its hint is shown; with none, just the full diagram.
   */
  diagramSteps?: [string, string][];
  related: { id: string; fit: string }[];
}

